import { test, expect } from '../fixtures/extension';
import { enableAutomaticBackups } from '../fixtures/automatic';

test('automatic controls persist and paused/off status appears in popup without blocking manual saves', async ({ extensionContext }, testInfo) => {
  const context = await extensionContext({ viewport: { width: 1200, height: 1400 } });
  const worker = context.serviceWorkers()[0] ?? await context.waitForEvent('serviceworker');
  const origin = `chrome-extension://${new URL(worker.url()).host}`;
  const page = await context.newPage();
  await page.goto(origin + '/backups.html#settings');
  await enableAutomaticBackups(page);
  await expect(page.getByRole('switch', { name: 'Enable backup limit' })).not.toBeChecked();
  await expect(page.getByRole('switch', { name: 'Enable time limit' })).not.toBeChecked();
  await expect(page.getByLabel('Count limit', { exact: true })).toHaveValue('5000');
  await expect(page.getByLabel('Count limit', { exact: true })).toBeDisabled();
  await expect(page.getByLabel('Time limit', { exact: true })).toBeDisabled();
  const automaticSaved = page.locator('.toast-region');
  const appearanceSaved = page.locator('.toast-region');
  const manual = page.locator('.history-main .backup-button');
  const enabled = page.getByRole('switch', { name: 'Automatic backups', exact: true });
  await expect(enabled).toBeChecked();
  await expect(enabled).toBeEnabled();
  await page.getByLabel('Backup frequency', { exact: true }).selectOption('5');
  await expect(enabled).toBeEnabled();
  await expect(automaticSaved).toHaveText('Settings have been saved');
  await expect(automaticSaved).toHaveText('Settings have been saved');
  await enabled.uncheck();
  await expect(page.locator('.settings-card .status-card').getByText('Automatic backups are off', { exact: true })).toBeVisible();
  await expect(automaticSaved).toHaveText('Settings have been saved');
  await page.reload();
  await expect(automaticSaved).toBeEmpty();
  await expect(enabled).not.toBeChecked();
  await expect(page.getByLabel('Backup frequency', { exact: true })).toHaveValue('5');
  await expect(page.getByLabel('Backup frequency', { exact: true })).toBeDisabled();
  await page.getByRole('link', { name: 'Backups', exact: true }).click();
  await manual.click();
  await expect(manual).toHaveText('Saved');
  await expect(manual).toBeEnabled();
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await expect(page.locator('.settings-card .status-card').getByText('Automatic backups are off', { exact: true })).toBeVisible();
  const popup = await context.newPage();
  await popup.goto(origin + '/popup.html');
  await expect(popup.getByText('Automatic backups are off')).toBeVisible();
  await popup.getByRole('button', { name: 'Back up now', exact: true }).click();
  await expect(popup.getByRole('button', { name: 'Saved', exact: true })).toBeDisabled();
  await enabled.check();
  await expect(enabled).toBeEnabled();
  await page.getByLabel('Backup frequency', { exact: true }).selectOption('0');
  await expect(enabled).toBeEnabled();
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Resume now' })).toBeVisible();
  await expect(automaticSaved).toHaveText('Settings have been saved');
  await expect(popup.getByText('Automatic backups are paused')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Resume now' })).toBeVisible();
  await page.getByLabel('Color theme').selectOption('dark');
  await expect(appearanceSaved).toHaveText('Settings have been saved');
  await expect(appearanceSaved).toHaveText('Settings have been saved');
  await expect(appearanceSaved).toBeEmpty();
  await page.getByLabel('Date format', { exact: true }).selectOption('exact');
  await expect(appearanceSaved).toHaveText('Settings have been saved');
  await expect(appearanceSaved).toHaveText('Settings have been saved');
  await page.screenshot({ path: testInfo.outputPath('automatic-dark.png'), fullPage: true });
  await page.setViewportSize({ width: 400, height: 1000 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Resume now' }).click();
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible();
  await expect(automaticSaved).toHaveText('Settings have been saved');
  await expect(automaticSaved).toBeEmpty();
  await expect(popup.getByText('Automatic backups are paused')).toHaveCount(0);
});
