import { test, expect } from '../fixtures/extension';
import { enableAutomaticBackups } from '../fixtures/automatic';

test('panel help supports hover, keyboard and touch without changing the page layout', async ({ extensionContext }, testInfo) => {
  const context = await extensionContext({ hasTouch: true, viewport: { width: 1280, height: 1200 } });
  const worker = context.serviceWorkers()[0] ?? await context.waitForEvent('serviceworker');
  const page = await context.newPage();
  await page.goto(`chrome-extension://${new URL(worker.url()).host}/backups.html`);
  await enableAutomaticBackups(page);
  const saved = page.getByRole('button', { name: 'About manual backups', exact: true });
  const automatic = page.getByRole('button', { name: 'About automatic backups', exact: true });
  await expect(saved).toBeVisible({ timeout: 2000 });
  const help = page.getByRole('tooltip');
  const toolbar = await page.locator('.archive-toolbar').boundingBox();
  await saved.hover();
  await expect(help).toContainText('Sessions you choose to keep until you delete them.');
  await expect(saved).toHaveAttribute('aria-expanded', 'true');
  expect(await page.locator('.archive-toolbar').boundingBox()).toEqual(toolbar);
  await help.hover();
  await expect(help).toBeVisible();
  await page.getByRole('heading', { name: 'Backups', exact: true }).hover();
  await expect(help).toHaveCount(0);
  await saved.focus();
  await expect(help).toBeVisible();
  await saved.press('Escape');
  await expect(help).toHaveCount(0);
  await expect(saved).toBeFocused();
  await expect(saved).toHaveAttribute('aria-expanded', 'false');
  await saved.press('Enter');
  await expect(help).toBeVisible();
  await page.keyboard.press('Tab');
  await expect(help).toHaveCount(0);
  await saved.click();
  await page.mouse.move(0, 0);
  await expect(help).toBeVisible();
  await page.getByRole('heading', { name: 'Backups', exact: true }).click();
  await expect(help).toHaveCount(0);
  await saved.click();
  await automatic.click();
  await expect(help).toHaveCount(1);
  await expect(help).toContainText('History of your tabs, windows, and tab groups.');
  await expect(saved).toHaveAttribute('aria-expanded', 'false');
  await page.setViewportSize({ width: 400, height: 900 });
  await saved.tap();
  await expect(help).toBeVisible();
  const bounds = await help.boundingBox();
  if (!bounds) throw new Error('Missing help popup');
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(400);
  await page.screenshot({ path: testInfo.outputPath('panel-help.png') });
  await saved.tap();
  await expect(help).toHaveCount(0);
  await saved.tap();
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await expect(help).toHaveCount(0);
});
